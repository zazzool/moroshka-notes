import {scan,titleOf,tagsOf,linksOf} from './markdown.mjs'

export const maxImageBytes=2*1024*1024
export const maxImageSide=2400
export const imageId=/^[0-9a-f]{64}$/
const reference=/^!\[Фото\]\(moroshka-media:([0-9a-f]{64})\)[ \t]*\r?$/
export function imageRefs(text){
  return [...new Set(scan(text).prose.map(({line})=>line.match(reference)?.[1]).filter(Boolean))]
}
export function stripImages(text){
  const ids=imageRefs(text)
  if(!ids.length)return text
  const prefix=ids.map(id=>'![Фото](moroshka-media:'+id+')').join('\n')+'\n\n'
  if(text.startsWith(prefix))return text.slice(prefix.length)
  const indexes=new Set(scan(text).prose.filter(({line})=>reference.test(line)).map(({index})=>index))
  return text.split('\n').filter((_,i)=>!indexes.has(i)).join('\n')
}
export function composeImages(text,ids){
  const unique=[...new Set(ids)]
  if(unique.length>128||unique.some(id=>!imageId.test(id)))throw Error('Некорректные изображения заметки')
  return unique.length?unique.map(id=>'![Фото](moroshka-media:'+id+')').join('\n')+'\n\n'+text:text
}
export function appendImage(text,id){
  if(!imageId.test(id))throw Error('Некорректный идентификатор изображения')
  return imageRefs(text).includes(id)?text:composeImages(stripImages(text),[...imageRefs(text),id])
}
export function feedContent(text){
  const body=scan(text).prose.map(({line})=>line.trim())
    .filter(line=>line&&!/^#{1,6}(?:\s|$)/.test(line)&&!reference.test(line)&&!/^(?:#[\p{L}\p{N}_-]+\s*)+$/u.test(line))
    .join(' ').replace(/\[\[([^\]]+)\]\]/g,'$1').replace(/\s+/g,' ').trim()
  const title=titleOf(text)
  return {body:body|| (title!=='Без названия'?title:imageRefs(text).length?'Фотозаметка':'Пустая заметка'),
    title, tags:tagsOf(text), links:linksOf(text).length, images:imageRefs(text).length}
}
// Only bounded JPEGs generated by the clients. Validate framing and SOF size
// before storing or sending to a provider; do not serve arbitrary MIME types.
export function validateJpeg(bytes){
  const b=bytes instanceof Uint8Array?bytes:new Uint8Array(bytes)
  if(b.length<16||b.length>maxImageBytes||b[0]!==255||b[1]!==216||b[b.length-2]!==255||b[b.length-1]!==217)
    throw Error('Ожидается JPEG до 2 МиБ')
  let i=2, size=null
  while(i<b.length-1){
    if(b[i++]!==255)throw Error('Повреждён JPEG')
    while(b[i]===255)i++
    const m=b[i++]
    if(m===217||m===218)break
    if(m===1||(m>=208&&m<=215))continue
    if(i+1>=b.length)throw Error('Повреждён JPEG')
    const len=b[i]*256+b[i+1]
    if(len<2||i+len>b.length)throw Error('Повреждён JPEG')
    if([192,193,194,195,197,198,199,201,202,203,205,206,207].includes(m)){
      if(len<8)throw Error('Повреждён JPEG')
      const h=b[i+3]*256+b[i+4],w=b[i+5]*256+b[i+6]
      if(!w||!h||w>maxImageSide||h>maxImageSide)throw Error('Размер изображения превышает 2400 пикселей')
      size={width:w,height:h}
    }
    i+=len
  }
  if(!size)throw Error('Не удалось определить размер JPEG')
  return size
}
